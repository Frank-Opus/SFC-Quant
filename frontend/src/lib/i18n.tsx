const LocaleContext = createContext<LocaleContextValue | null>(null);

function loadInitialLocale(): Locale {
  if (typeof window === "undefined") {
    return "zh-CN";
  }

  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "zh-CN") {
    return stored;
  }

  LEGACY_STORAGE_KEYS.forEach((key) => {
    window.localStorage.removeItem(key);
  });
  return "zh-CN";
}

function interpolate(template: string, params: MessageParams): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

function resolveMessage(locale: Locale, key: string, params: MessageParams): string {
  const table = messages[locale];
  const fallbackTable = messages.en;
  const value = table[key] ?? fallbackTable[key];
  if (!value) {
    return key;
  }
  if (typeof value === "function") {
    return value(params);
  }
  return interpolate(value, params);
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(loadInitialLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => {
    const t = (key: string, params: MessageParams = {}) => resolveMessage(locale, key, params);

    return {
      locale,
      setLocale: setLocaleState,
      toggleLocale: () => setLocaleState((current) => (current === "en" ? "zh-CN" : "en")),
      t,
      formatCurrency: (value: number) =>
        new Intl.NumberFormat(locale, {
          style: "currency",
          currency: "USD",
          currencyDisplay: "narrowSymbol",
          maximumFractionDigits: 2,
        }).format(value),
      formatCompactNumber: (value: number) =>
        new Intl.NumberFormat(locale, {
          notation: "compact",
          maximumFractionDigits: 2,
        }).format(value),
      formatNumber: (value: number, maximumFractionDigits = 0) =>
        new Intl.NumberFormat(locale, {
          maximumFractionDigits,
        }).format(value),
      formatPercent: (value: number, showPlus = true) => {
        const formatted = new Intl.NumberFormat(locale, {
          minimumFractionDigits: 2,
          maximumFractionDigits: 2,
        }).format(value);
        return `${value >= 0 && showPlus ? "+" : ""}${formatted}%`;
      },
      formatTime: (value: string | number | Date) =>
        new Intl.DateTimeFormat(locale, {
          hour: "2-digit",
          minute: "2-digit",
          second: "2-digit",
        }).format(new Date(value)),
      formatDateTime: (value: string | number | Date) =>
        new Intl.DateTimeFormat(locale, {
          year: "numeric",
          month: "2-digit",
          day: "2-digit",
          hour: "2-digit",
          minute: "2-digit",
        }).format(new Date(value)),
      formatRecommendation: (
        recommendation: Recommendation,
        options: { uppercase?: boolean } = {},
      ) => {
        const label = t(`recommendation.${recommendation}`);
        return options.uppercase && locale === "en" ? label.toUpperCase() : label;
      },
      formatRole: (role: AgentRole) => t(`role.${role}`),
    };
  }, [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used within LocaleProvider");
  }
  return context;
}
